#!/usr/bin/env python3
"""Export The Gauntlet's game data (Python constants) to Luau modules.

Usage:
    python tools/export_data.py <path-to-The-Gauntlet-checkout> [--out src/shared/Data/Generated]

Run again after every GitHub update. Output files are overwritten; never edit
them by hand. Logic (combat, AI, world building) is ported manually in src/.
"""
import argparse
import importlib
import math
import re
import subprocess
import sys
from pathlib import Path

# Modules whose UPPERCASE constants become Data/Generated/<Name>.luau.
MODULES = [
    "adventure", "dungeons", "region_content", "hero_skills", "enemy_roles",
    "tactical_rules", "progression", "ascension", "magic_runes", "soul_crystal",
    "cottage", "puzzles", "exploration_movement", "enemy_awareness",
    "combat_environment", "boss_ai", "companion_ai", "adventure_rewards",
    "chapter_flow", "opening", "dialogue_choices", "village_portals",
    "interactions", "outdoor_respawns", "acquisitions", "skill_casts",
    "ability_visuals", "ability_animations", "town_layout",
]
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
            "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue"}
SKIP = object()


def pascal(name):
    return "".join(p.capitalize() for p in name.split("_"))


def lua_str(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"': out.append('\\"')
        elif ch == "\\": out.append("\\\\")
        elif ch == "\n": out.append("\\n")
        elif ch == "\r": out.append("\\r")
        elif ch == "\t": out.append("\\t")
        elif o < 32: out.append("\\%d" % o)
        else: out.append(ch)
    out.append('"')
    return "".join(out)


def key_text(k):
    if isinstance(k, tuple):
        k = "|".join(str(x) for x in k)
    if isinstance(k, bool):
        return "[%s]" % ("true" if k else "false")
    if isinstance(k, int):
        return "[%d]" % k
    if isinstance(k, float):
        return "[%r]" % k
    k = str(k)
    if IDENT.match(k) and k not in RESERVED:
        return k
    return "[%s]" % lua_str(k)


def ser(v, depth=0):
    """Return Luau source for v, or SKIP if v cannot be represented."""
    pad = "\t" * (depth + 1)
    end = "\t" * depth
    if v is None: return "nil"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, float):
        if math.isnan(v) or math.isinf(v): return SKIP
        return repr(v)
    if isinstance(v, str): return lua_str(v)
    if isinstance(v, (list, tuple, set, frozenset)):
        items = sorted(v, key=repr) if isinstance(v, (set, frozenset)) else v
        parts = []
        for x in items:
            s = ser(x, depth + 1)
            parts.append("nil" if s is SKIP else s)
        if not parts: return "{}"
        if all(len(p) < 24 and "\n" not in p for p in parts) and len(parts) <= 12:
            return "{ " + ", ".join(parts) + " }"
        return "{\n" + "".join("%s%s,\n" % (pad, p) for p in parts) + end + "}"
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            if not isinstance(k, (str, int, float, bool, tuple)): continue
            s = ser(x, depth + 1)
            if s is SKIP: continue
            parts.append("%s%s = %s,\n" % (pad, key_text(k), s))
        if not parts: return "{}"
        return "{\n" + "".join(parts) + end + "}"
    return SKIP


def header(src_label):
    return ("--!nocheck\n-- AUTO-GENERATED by tools/export_data.py from %s.\n"
            "-- DO NOT EDIT. Re-run the exporter after every GitHub update.\n" % src_label)


def write_module(path, label, table_src):
    path.write_text(header(label) + "return " + table_src + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo", help="path to a checkout of The-Gauntlet")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "src/shared/Data/Generated"))
    args = ap.parse_args()
    repo = Path(args.repo).resolve()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.luau"):
        old.unlink()
    sys.path.insert(0, str(repo))
    try:
        commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
                                capture_output=True, text=True).stdout.strip() or "unknown"
    except OSError:
        commit = "unknown"
    label = "The-Gauntlet @ " + commit
    written, skipped = [], []

    # game.py: curated, so ability tuples become named records.
    import game
    curated = {
        "Heroes": game.CLASSES,
        "Abilities": {
            "sets": {hero: [game.ability_record(a) for a in abilities] for hero, abilities in game.ABILITY_SETS.items()},
            "summons": game.SUMMON_TYPES,
        },
        "Items": {"items": game.ITEMS, "classWeapons": game.CLASS_WEAPONS,
                  "lootRarities": [list(r) for r in game.LOOT_RARITIES], "curses": game.CURSES},
        "Enemies": {
            "regular": [dict(name=e[0], kind=e[1], hp=e[2], damage=e[3], color=e[4]) for e in game.ENEMIES],
            "draco": dict(name=game.DRACO[0], kind=game.DRACO[1], hp=game.DRACO[2], damage=game.DRACO[3], color=game.DRACO[4]),
            "largeBosses": game.LARGE_BOSSES, "dragonTypes": game.DRAGON_TYPES, "affinities": game.AFFINITIES,
        },
        "GameCore": {"width": game.WIDTH, "height": game.HEIGHT, "maxPlayers": game.MAX_PLAYERS,
                     "pouchCapacity": game.POUCH_CAPACITY, "difficulties": game.DIFFICULTIES},
    }
    for name, value in curated.items():
        write_module(out / (name + ".luau"), label, ser(value))
        written.append(name)

    for modname in MODULES:
        try:
            mod = importlib.import_module(modname)
        except Exception as exc:  # keep going; report at the end
            skipped.append("%s (import failed: %s)" % (modname, exc))
            continue
        if hasattr(mod, "setup") and modname == "hero_skills":
            mod.setup()  # TREES is built lazily
        consts = {}
        for k in dir(mod):
            if not k.isupper() or k.startswith("_"): continue
            s = ser(getattr(mod, k))
            if s is not SKIP:
                consts[k] = getattr(mod, k)
        if not consts:
            skipped.append("%s (no serialisable constants)" % modname)
            continue
        write_module(out / (pascal(modname) + ".luau"), label, ser(consts))
        written.append(pascal(modname))

    index = header(label) + "-- Lazy index of every generated data module.\nlocal Generated = {}\n"
    for name in sorted(written):
        index += 'Generated.%s = require(script.Generated.%s)\n' % (name, name)
    index += "Generated._source = %s\nreturn Generated\n" % lua_str(label)
    # init.luau makes Data/ itself a ModuleScript with Generated/ as its child.
    (out.parent / "init.luau").write_text(index, encoding="utf-8")
    print("Exported %d modules from %s -> %s" % (len(written), label, out))
    for s in skipped:
        print("  skipped:", s)


if __name__ == "__main__":
    main()
